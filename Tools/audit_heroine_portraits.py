"""Audit heroine portrait coverage against the original dumper manifest.
--repair installs missing native frames and supplied redesigns, without replacing existing images.
"""
from pathlib import Path
import argparse, json, re, shutil, uuid
from PIL import Image
PROJECT=Path(__file__).resolve().parents[1]
ASSETS=PROJECT/'Assets'
NAMES={'Nico','Selfi','Patty','Miya','Vivian','Cherrl','Fur'}
def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--repair',action='store_true');a=ap.parse_args()
 manifest=json.loads((ASSETS/'AzureDreams/Data/Extracted/AdResourcesDumper/manifest.json').read_text(encoding='utf-8'))
 entries=[e for e in manifest['portraits'] if e['speaker'] in NAMES]
 native=ASSETS/'StreamingAssets/Media/Portraits/Dialogue';source=ASSETS/'AzureDreams/Sprites/Portraits/AdResourcesDumper/Frames'
 overlay=ASSETS/'StreamingAssets/Media/Reimagined/Portraits/Dialogue';supplied=PROJECT.parent/'_Redesigned assets/Portraits'
 expected={e['file']:e for e in entries};added=[];missing=[];invalid=[]
 def install(src,dst):
  if dst.exists():return
  if a.repair:
   shutil.copyfile(src,dst)
   meta=dst.with_name(dst.name+'.meta')
   if not meta.exists():meta.write_text('fileFormatVersion: 2\nguid: '+uuid.uuid5(uuid.NAMESPACE_URL,'azure/portrait/'+str(dst.relative_to(ASSETS))).hex+'\n',encoding='utf-8')
  added.append(str(dst.relative_to(ASSETS)))
 for e in entries:
  canonical=e['file'].replace('_variant','Retail_variant')
  if not (native/canonical).exists():
   if (source/e['file']).exists():install(source/e['file'],native/canonical)
   else:missing.append(canonical)
 for p in sorted(supplied.glob('*.png')):
  name=re.sub(r' - (?:Copia|Copy)(?: \(\d+\))?(?=\.png$)','',p.name,flags=re.I)
  generic=name.replace('Retail_variant','_variant')
  if generic not in expected:continue
  install(p,overlay/name)
 for e in entries:
  p=native/e['file'].replace('_variant','Retail_variant')
  if not p.exists():missing.append(p.name);continue
  with Image.open(p) as im:
   if im.size!=(e['width'],e['height']) or im.convert('RGBA').getbbox() is None:invalid.append(p.name)
 if a.repair:
  index=ASSETS/'AzureDreams/Resources/Reimagined/media_overlay.txt'
  media=ASSETS/'StreamingAssets/Media';root=media/'Reimagined'
  lines=['# Generated by ReimaginedMediaManifest. Paths are relative to StreamingAssets/Media/Reimagined.']
  for key in sorted(p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file() and p.suffix.lower()!='.meta'):
   classic=media/key
   counterpart=classic.exists() or (key.startswith('Music/') and any(classic.with_suffix(ext).exists() for ext in ('.ogg','.mp3')))
   lines.append(key+('' if counterpart else '\t*'))
  index.write_text('\n'.join(lines)+'\n',encoding='utf-8')
 summary=[]
 for speaker in sorted(NAMES):
  rows=[e for e in entries if e['speaker']==speaker]
  summary.append(dict(speaker=speaker,variants=len({e['variant'] for e in rows}),frames=len(rows),redesigned_frames=sum((overlay/e['file']).exists() or (overlay/e['file'].replace('_variant','Retail_variant')).exists() for e in rows)))
 report=dict(summary=summary,added=added,missing_native=missing,invalid_native=invalid,repair=a.repair)
 target=PROJECT.parent/'Validation/PortraitAudit';target.mkdir(parents=True,exist_ok=True);(target/'coverage.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
 print(json.dumps(report,indent=2))
 if missing or invalid:raise SystemExit(1)
if __name__=='__main__':main()
