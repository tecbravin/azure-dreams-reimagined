using System;
using System.Collections.Generic;
using UnityEngine;
using Object = UnityEngine.Object;

namespace AzureDreamsReimagined
{
    /// <summary>Visual/audio style chosen by the player. Reimagined is the default.</summary>
    public enum ArtStyle
    {
        Reimagined = 0,
        Classic = 1
    }

    /// <summary>
    /// Chooses between the redesigned asset set (Reimagined, default) and the original game assets (Classic).
    ///
    /// Convention: original assets keep their normal path. A redesigned replacement uses the SAME relative
    /// path under an overlay folder named "Reimagined":
    ///   Assets/AzureDreams/Resources/Reimagined/&lt;path&gt;      → loaded through <see cref="Load{T}"/>
    ///   Assets/StreamingAssets/Media/Reimagined/&lt;path&gt;      → resolved through <see cref="ResolveMedia"/>
    /// Reimagined uses the overlay when it exists and falls back to the original. Classic never reads the overlay.
    ///
    /// StreamingAssets cannot be listed on WebGL, so the overlay contents are indexed in
    /// Resources/Reimagined/media_overlay.txt, regenerated by the editor (ReimaginedMediaManifest).
    /// Each line is a path relative to Media/Reimagined; a trailing "\t*" marks a redesigned-only file
    /// that has no original counterpart (Classic shows nothing for it).
    /// </summary>
    public static class AssetMode
    {
        public const string Preference = "ad_asset_mode";
        public const string OverlayFolder = "Reimagined";
        public const string MediaManifestResource = OverlayFolder + "/media_overlay";
        public const char ReimaginedOnlyMarker = '*';

        private static ArtStyle? _current;
        private static HashSet<string> _mediaOverlay;
        private static HashSet<string> _reimaginedOnlyMedia;

        /// <summary>Raised after the style changes, so caches can be dropped and music reloaded.</summary>
        public static event Action Changed;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        private static void ResetState()
        {
            _current = null;
            _mediaOverlay = null;
            _reimaginedOnlyMedia = null;
            Changed = null;
        }

        public static ArtStyle Current =>
            _current ??= PlayerPrefs.GetInt(Preference, (int)ArtStyle.Reimagined) == (int)ArtStyle.Classic
                ? ArtStyle.Classic
                : ArtStyle.Reimagined;

        public static bool IsReimagined => Current == ArtStyle.Reimagined;
        public static bool IsClassic => Current == ArtStyle.Classic;

        public static void Select(ArtStyle style, bool save = true)
        {
            bool changed = Current != style;
            _current = style;
            if (save)
            {
                PlayerPrefs.SetInt(Preference, (int)style);
                PlayerPrefs.Save();
            }
            if (changed) Changed?.Invoke();
        }

        public static void Toggle() => Select(IsReimagined ? ArtStyle.Classic : ArtStyle.Reimagined);

        /// <summary>Resources.Load that prefers Resources/Reimagined/&lt;path&gt; in Reimagined mode.</summary>
        public static T Load<T>(string path) where T : Object
        {
            if (IsReimagined && !string.IsNullOrEmpty(path))
            {
                var overlay = Resources.Load<T>(OverlayFolder + "/" + path);
                if (overlay) return overlay;
            }
            return Resources.Load<T>(path);
        }

        /// <summary>True when Media/Reimagined/&lt;relativePath&gt; exists.</summary>
        public static bool HasMediaOverlay(string relativePath)
        {
            EnsureMediaOverlay();
            return _mediaOverlay.Contains(Normalize(relativePath));
        }

        /// <summary>True when the file exists only as a redesigned asset (no original to fall back to).</summary>
        public static bool IsReimaginedOnlyMedia(string relativePath)
        {
            EnsureMediaOverlay();
            return _reimaginedOnlyMedia.Contains(Normalize(relativePath));
        }

        /// <summary>
        /// Path relative to StreamingAssets/Media for the current style, or null when Classic has
        /// no original version of a redesigned-only file.
        /// </summary>
        public static string ResolveMedia(string relativePath)
        {
            if (string.IsNullOrEmpty(relativePath)) return relativePath;
            string path = Normalize(relativePath);
            if (IsReimagined) return HasMediaOverlay(path) ? OverlayFolder + "/" + path : path;
            return IsReimaginedOnlyMedia(path) ? null : path;
        }

        /// <summary>Replaces the overlay index (used by tests and by the editor after regenerating it).</summary>
        public static void SetMediaOverlay(string manifestText)
        {
            _mediaOverlay = new HashSet<string>(StringComparer.Ordinal);
            _reimaginedOnlyMedia = new HashSet<string>(StringComparer.Ordinal);
            if (string.IsNullOrEmpty(manifestText)) return;
            foreach (string raw in manifestText.Split('\n'))
            {
                string line = raw.TrimEnd('\r');
                if (line.Length == 0 || line[0] == '#') continue;
                int tab = line.IndexOf('\t');
                string path = Normalize(tab >= 0 ? line[..tab] : line);
                _mediaOverlay.Add(path);
                if (tab >= 0 && line.IndexOf(ReimaginedOnlyMarker, tab) > tab) _reimaginedOnlyMedia.Add(path);
            }
        }

        private static void EnsureMediaOverlay()
        {
            if (_mediaOverlay != null) return;
            var manifest = Resources.Load<TextAsset>(MediaManifestResource);
            SetMediaOverlay(manifest ? manifest.text : null);
            if (manifest) Resources.UnloadAsset(manifest);
        }

        private static string Normalize(string path) => path.Replace('\\', '/').TrimStart('/');
    }
}
