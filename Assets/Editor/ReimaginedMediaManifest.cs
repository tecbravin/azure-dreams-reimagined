using System;
using System.IO;
using System.Linq;
using System.Text;
using AzureDreamsReimagined;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace AzureDreamsReimagined.Editor
{
    /// <summary>
    /// Keeps Resources/Reimagined/media_overlay.txt in sync with StreamingAssets/Media/Reimagined.
    /// The runtime needs this index because StreamingAssets cannot be listed on WebGL.
    /// Regenerated on import changes under Media/Reimagined, before every build, and from the menu.
    /// </summary>
    public sealed class ReimaginedMediaManifest : AssetPostprocessor, IPreprocessBuildWithReport
    {
        public const string MediaRoot = "Assets/StreamingAssets/Media";
        public const string OverlayRoot = MediaRoot + "/" + AssetMode.OverlayFolder;
        public const string ManifestPath = "Assets/AzureDreams/Resources/" + AssetMode.MediaManifestResource + ".txt";

        public int callbackOrder => 0;

        public void OnPreprocessBuild(BuildReport report) => Rebuild();

        [MenuItem("Azure Dreams/Rebuild Reimagined Media Manifest")]
        public static void RebuildFromMenu()
        {
            bool changed = Rebuild();
            Debug.Log(changed ? "[Reimagined] media_overlay.txt updated." : "[Reimagined] media_overlay.txt already up to date.");
        }

        private static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
        {
            static bool Touches(string path) => path.StartsWith(OverlayRoot + "/", StringComparison.Ordinal);
            if (imported.Any(Touches) || deleted.Any(Touches) || moved.Any(Touches) || movedFrom.Any(Touches))
                Rebuild();
        }

        /// <summary>Builds the manifest text from the folders on disk.</summary>
        public static string Build(string mediaRoot, string overlayRoot)
        {
            var text = new StringBuilder("# Generated by ReimaginedMediaManifest. Paths are relative to StreamingAssets/Media/Reimagined.\n");
            if (!Directory.Exists(overlayRoot)) return text.ToString();
            var files = Directory.GetFiles(overlayRoot, "*", SearchOption.AllDirectories)
                .Where(path => !path.EndsWith(".meta", StringComparison.OrdinalIgnoreCase))
                .Select(path => Path.GetRelativePath(overlayRoot, path).Replace('\\', '/'))
                .OrderBy(path => path, StringComparer.Ordinal);
            foreach (string relative in files)
            {
                text.Append(relative);
                if (!HasClassicCounterpart(mediaRoot, relative)) text.Append('\t').Append(AssetMode.ReimaginedOnlyMarker);
                text.Append('\n');
            }
            return text.ToString();
        }

        // Music may change container between versions (Tower1.ogg ↔ Tower1.mp3), so any extension counts.
        private static bool HasClassicCounterpart(string mediaRoot, string relative)
        {
            if (File.Exists(Path.Combine(mediaRoot, relative))) return true;
            if (!relative.StartsWith("Music/", StringComparison.Ordinal)) return false;
            string stem = Path.Combine(mediaRoot, Path.ChangeExtension(relative, null));
            return File.Exists(stem + ".ogg") || File.Exists(stem + ".mp3");
        }

        /// <summary>Writes the manifest when its content changed. Returns true if it was written.</summary>
        public static bool Rebuild()
        {
            string content = Build(MediaRoot, OverlayRoot);
            if (File.Exists(ManifestPath) && File.ReadAllText(ManifestPath) == content) return false;
            Directory.CreateDirectory(Path.GetDirectoryName(ManifestPath)!);
            File.WriteAllText(ManifestPath, content);
            AssetDatabase.ImportAsset(ManifestPath);
            AssetMode.SetMediaOverlay(content);
            return true;
        }
    }
}
